def nat1(lon, lat):
    """d3.geoNaturalEarth1 raw projection (unscaled), radians in"""
    l, p = math.radians(lon), math.radians(lat)
    p2 = p * p; p4 = p2 * p2
    return (l * (0.8707 - 0.131979 * p2 + p4 * (-0.013791 + p4 * (0.003971 * p2 - 0.001529 * p4))),
            p * (1.007226 + p2 * (0.015085 + p4 * (-0.044475 + 0.028874 * p2 - 0.005916 * p4))))


def nat1_inv(x, y):
    p = y
    for _ in range(25):
        p2 = p * p; p4 = p2 * p2
        fy = p * (1.007226 + p2 * (0.015085 + p4 * (-0.044475 + 0.028874 * p2 - 0.005916 * p4))) - y
        dy = 1.007226 + p2 * (3 * 0.015085 + p4 * (7 * -0.044475 + 9 * 0.028874 * p2 - 11 * 0.005916 * p4))
        p -= fy / dy
    p2 = p * p; p4 = p2 * p2
    l = x / (0.8707 - 0.131979 * p2 + p4 * (-0.013791 + p4 * (0.003971 * p2 - 0.001529 * p4)))
    return math.degrees(l), math.degrees(p)


def check():
    from shapely.geometry import shape, Point
    from shapely.prepared import prep
    land = prep(shape(json.load(open(os.path.join(ROOT, 'data', 'land.json')))['geometry']))
    bad = 0
    for r in ROUTES:
        assert r['from'] < r['to'], r['name']
        if r['kind'] not in SEA or r['river']:
            continue
        pts = r['path']
        for i in range(1, len(pts)):
            a, b = pts[i - 1], pts[i]
            if abs(a[0] - b[0]) > 180:
                continue
            (ax, ay), (bx, by) = nat1(*a), nat1(*b)
            n = max(2, int(math.hypot(bx - ax, by - ay) / 0.0015))
            run = []
            for j in range(1, n):
                u = j / n
                lon, lat = nat1_inv(ax + (bx - ax) * u, ay + (by - ay) * u)
                near = min(math.hypot(lon - a[0], lat - a[1]), math.hypot(lon - b[0], lat - b[1])) < 0.35
                if not near and land.contains(Point(lon, lat)):
                    run.append((round(lon, 2), round(lat, 2)))
            if run:
                bad += 1
                print(f"LAND {r['name']}: leg {i} {a} -> {b} crosses land at {run[0]}..{run[-1]} ({len(run)} samples)")
    return bad


if __name__ == '__main__':
    bad = check()
    out = {'routes': [{k: r[k] for k in ('kind', 'from', 'to', 'color')} | {'path': [[round(c, 2) for c in p] for p in r['path']]} for r in ROUTES]}
    json.dump(out, open(os.path.join(ROOT, 'data', 'ambient.json'), 'w'), separators=(',', ':'), ensure_ascii=False)
    print(f'{len(ROUTES)} routes, {bad} legs over land, {os.path.getsize(os.path.join(ROOT, "data", "ambient.json")) // 1024} KB')
